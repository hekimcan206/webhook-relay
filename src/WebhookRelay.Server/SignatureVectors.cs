using System.Text;
using System.Text.Json;
using WebhookRelay.Signing;

namespace WebhookRelay.Server;

/// <summary>
/// Deterministic signature test vectors produced by the relay's own signer. CI regenerates them, checks they match the
/// committed copy, and runs the C#, Node and Python receiver samples against them: positive cases must verify,
/// negative cases must be rejected. That is the cross-language contract, not just a self-consistency check.
/// </summary>
internal static class SignatureVectors
{
    // Fixed, synthetic keys: vectors must be reproducible byte for byte.
    private static readonly WebhookSecret Primary = WebhookSecret.FromBytes(Enumerable.Range(1, 32).Select(i => (byte)i).ToArray());
    private static readonly WebhookSecret Rotated = WebhookSecret.FromBytes(Enumerable.Range(101, 32).Select(i => (byte)i).ToArray());
    private static readonly WebhookSecret Unrelated = WebhookSecret.FromBytes(Enumerable.Range(201, 48).Select(i => (byte)i).ToArray());
    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web)
    {
        WriteIndented = true,
        Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
    };

    private const long Timestamp = 1_790_000_000;
    private const string MessageId = "msg_0193f0a2b7c87f5e9d4c3b2a19087654";

    private sealed record Vector(
        string Name, string[] ReceiverSecrets, string? WebhookId, string? WebhookTimestamp, string? WebhookSignature,
        string BodyBase64, long Now, bool ExpectValid);

    public static string Generate()
    {
        var simple = Bytes("""{"type":"invoice.paid","data":{"invoiceId":"inv_001","amount":"1250.00","currency":"TRY"}}""");
        var unicode = Bytes("""{"type":"customer.updated","data":{"name":"Şükrü Öztürk","city":"İzmir","note":"çay ☕ 🚀"}}""");
        var whitespace = Bytes("{ \"type\" : \"spaced\",\n  \"data\" : [1, 2, 3] }\n");
        var large = Bytes("{\"type\":\"bulk\",\"data\":\"" + new string('x', 65_536) + "\"}");
        var both = new[] { Rotated, Primary };

        var vectors = new List<Vector>
        {
            Valid("simple", [Primary], simple, [Primary]),
            Valid("unicode-body", [Primary], unicode, [Primary]),
            Valid("whitespace-is-significant", [Primary], whitespace, [Primary]),
            Valid("empty-object", [Primary], Bytes("{}"), [Primary]),
            Valid("large-64k-body", [Primary], large, [Primary]),
            Valid("rotation-receiver-has-old-secret", both, simple, [Primary]),
            Valid("rotation-receiver-has-new-secret", both, simple, [Rotated]),
            Valid("receiver-holds-two-secrets", [Rotated], simple, [Primary, Rotated]),
            Valid("tolerance-edge-old", [Primary], simple, [Primary], now: Timestamp + 300),
            Valid("tolerance-edge-new", [Primary], simple, [Primary], now: Timestamp - 300),
            Valid("unknown-version-entries-skipped", [Primary], simple, [Primary], prefix: "v1a,AAAA v2,BBBB "),

            Invalid("tampered-body", Sign([Primary], simple), Bytes("""{"type":"invoice.paid","data":{"invoiceId":"inv_001","amount":"9250.00","currency":"TRY"}}"""), [Primary]),
            Invalid("reserialised-body", Sign([Primary], whitespace), Bytes("""{"type":"spaced","data":[1,2,3]}"""), [Primary]),
            Invalid("wrong-secret", Sign([Primary], simple), simple, [Unrelated]),
            Invalid("timestamp-too-old", Sign([Primary], simple), simple, [Primary], now: Timestamp + 301),
            Invalid("timestamp-too-new", Sign([Primary], simple), simple, [Primary], now: Timestamp - 301),
            Invalid("signature-for-other-id", Sign([Primary], simple), simple, [Primary], id: "msg_0193f0a2b7c87f5e9d4c3b2a19087655"),
            Invalid("signature-for-other-timestamp", Sign([Primary], simple), simple, [Primary], timestamp: (Timestamp + 1).ToString(System.Globalization.CultureInfo.InvariantCulture)),
            Invalid("only-unknown-versions", "v1a," + Sign([Primary], simple)[3..], simple, [Primary]),
            Invalid("malformed-signature", "v1,not-base64!!", simple, [Primary]),
            Invalid("missing-signature", null, simple, [Primary]),
            Invalid("non-numeric-timestamp", Sign([Primary], simple), simple, [Primary], timestamp: "1790000000.0"),
        };

        return JsonSerializer.Serialize(new
        {
            description = "Standard Webhooks v1 signature vectors generated by webhook-relay (RelayApp --emit-vectors). Synthetic keys.",
            toleranceSeconds = 300,
            vectors,
        }, JsonOptions) + "\n";

        static Vector Valid(string name, WebhookSecret[] signers, byte[] body, WebhookSecret[] receiver, long now = Timestamp, string prefix = "") =>
            new(name, Encode(receiver), MessageId, Ts(Timestamp), prefix + Sign(signers, body), Convert.ToBase64String(body), now, true);

        static Vector Invalid(string name, string? signature, byte[] body, WebhookSecret[] receiver, long now = Timestamp, string id = MessageId, string? timestamp = null) =>
            new(name, Encode(receiver), id, timestamp ?? Ts(Timestamp), signature, Convert.ToBase64String(body), now, false);
    }

    private static string Sign(WebhookSecret[] secrets, byte[] body) => WebhookSigner.SignatureHeader(secrets, MessageId, Timestamp, body);

    private static string[] Encode(WebhookSecret[] secrets) => [.. secrets.Select(s => s.Encoded)];

    private static string Ts(long value) => value.ToString(System.Globalization.CultureInfo.InvariantCulture);

    private static byte[] Bytes(string value) => Encoding.UTF8.GetBytes(value);
}
